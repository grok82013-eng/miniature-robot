logging.basicConfig(
    format="%(asctime)s [%(levelname)s] %(message)s",
    level=logging.INFO
)
log = logging.getLogger(__name__)


def is_work_time() -> bool:
    now = datetime.now().time()
    return WORK_START <= now < WORK_END


async def phrase_loop(bot: Bot):
    pool = PHRASES.copy()
    random.shuffle(pool)
    idx = 0
    while True:
        jitter = random.randint(-30, 30)
        await asyncio.sleep(INTERVAL + jitter)

        if not is_work_time():
            log.info("Не рабочее время, пропускаю.")
            continue

        if idx >= len(pool):
            random.shuffle(pool)
            idx = 0
        phrase = pool[idx]
        idx += 1

        try:
            await bot.send_message(chat_id=CHAT_ID, text=phrase)
            log.info(f"Отправил [{idx}]: {phrase[:50]}...")
        except Exception as e:
            log.error(f"Ошибка: {e}")


async def main():
    log.info("Бот запускается...")
    bot = Bot(token=PLAYER_TOKEN)
    me = await bot.get_me()
    log.info(f"Авторизован как @{me.username}")
    await phrase_loop(bot)


if __name__ == "__main__":
    asyncio.run(main())
